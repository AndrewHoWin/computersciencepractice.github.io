    shuffle(arr) {
        const copy = [...arr];
        for (let i = copy.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [copy[i], copy[j]] = [copy[j], copy[i]];
        }
        return copy;
    }

    escapeHtml(str) {
        if (str === null || str === undefined) return "";
        return String(str)
            .replace(/&/g, "&amp;")
            .replace(/</g, "&lt;")
            .replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;")
            .replace(/'/g, "&#039;");
    }

    cleanCoreText(rawText, isSingle) {
        if (!rawText) return "";
        let text = String(rawText)
            .replace(/【零基础保姆级解析】\s*/g, "")
            .replace(/零基础保姆级/g, "")
            .replace(/保姆级/g, "")
            .replace(/这道题有个超简单的偷懒办法：/g, "简便计算方法如下：")
            .replace(/最傻瓜的/g, "直接的")
            .replace(/“偷懒短路”/g, "“短路求值”")
            .replace(/小心出题老师的障眼法！/g, "注意审题细节：")
            .replace(/别被“统计词数”的题目文字骗了，我们要看代码实际在干什么：/g, "结合代码实际运行逻辑分析：")
            .replace(/千万别掉进陷阱里！/g, "注意初始值设置：")
            .replace(/又是一道经典的“初值陷阱题”！/g, "注意变量的初始值：")
            .replace(/这位可爱的同学/g, "该程序")
            .replace(/睁大眼睛看|睜大眼睛看/g, "注意观察")
            .replace(/直接被咔嚓切掉了/g, "会被直接截断舍弃")
            .replace(/像找茬游戏一样/g, "逐项")
            .replace(/掰着手指头/g, "依次")
            .replace(/张冠李戴啦！/g, "注意区分概念：")
            .replace(/说反啦！|说反了！/g, "表述相反。")
            .replace(/立刻秒答：/g, "可直接得出：")
            .replace(/秒杀|秒选/g, "快速得出")
            .trim();

        if (!isSingle) {
            return text;
        }

        const lines = text.split("\n").filter(line => {
            const t = line.trim();
            if (!t) return false;
            if (/^[-•]?\s*(\d+\.\s*)?(只有)?(先看|再看|看|对比)?\s*(选项\s*[A-D]|[A-D]\s*选项|[A-D]\s*[：:\.错对])/i.test(t)) return false;
            if (/^(所以|因此|故|可见|按原卷|按照原卷|综上所述).*?(选|答案是|答案为)\s*[A-D]/i.test(t)) return false;
            if (/^(题目问的是|题目要求选出|我们逐项|我们来看看|我们逐个)/i.test(t)) return false;
            return true;
        }).map(line => {
            return line
                .replace(/（[^）]*?(排除|选项|选\s*[A-D]|[A-D]\s*选项)[^）]*?）/g, "")
                .replace(/[，,；;。]?\s*(因此|所以|故)?(直接)?(选|锁定|排除)\s*(选项)?\s*[A-D][！!。.]*$/g, "。");
        });

        return lines.join("\n").trim();
    }

